CREATE OR REPLACE FUNCTION fn_densidad_no_solapada()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path TO iqbf, pg_catalog, pg_temp
AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext(NEW.id_presentacion));
  IF EXISTS (
      SELECT 1
        FROM densidad_vigencia d
       WHERE d.id_presentacion = NEW.id_presentacion
         AND d.id_densidad <> COALESCE(NEW.id_densidad, -1)
         AND daterange(d.vigencia_desde, COALESCE(d.vigencia_hasta, 'infinity'::date), '[]')
             && daterange(NEW.vigencia_desde, COALESCE(NEW.vigencia_hasta, 'infinity'::date), '[]')
  ) THEN
    RAISE EXCEPTION 'La presentacion % ya tiene una densidad vigente en ese periodo',
                    NEW.id_presentacion;
  END IF;
  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS tg_densidad_no_solapada ON densidad_vigencia;
CREATE TRIGGER tg_densidad_no_solapada
BEFORE INSERT OR UPDATE ON densidad_vigencia
FOR EACH ROW EXECUTE FUNCTION fn_densidad_no_solapada();

INSERT INTO densidad_vigencia
    (id_presentacion, valor, fuente, vigencia_desde)
SELECT id_presentacion, densidad, 'MIGRACION_PRESENTACION', DATE '1900-01-01'
  FROM presentacion p
 WHERE densidad IS NOT NULL
   AND NOT EXISTS (
       SELECT 1
         FROM densidad_vigencia d
        WHERE d.id_presentacion = p.id_presentacion
   );

-- Bitácora transversal. El backend fija iqbf.actor_id e iqbf.request_id dentro
-- de cada transacción; los cambios directos siguen quedando registrados.
CREATE TABLE IF NOT EXISTS bitacora (
    id_evento      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora     TIMESTAMPTZ NOT NULL DEFAULT now(),
    id_usuario     INTEGER REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    accion         VARCHAR(12) NOT NULL,
    entidad        VARCHAR(80) NOT NULL,
    entidad_id     TEXT,
    valores_antes  JSONB,
    valores_despues JSONB,
    request_id     UUID,
    origen         VARCHAR(20) NOT NULL DEFAULT 'BD'
);
CREATE INDEX IF NOT EXISTS ix_bitacora_entidad
    ON bitacora (entidad, entidad_id, fecha_hora DESC);
CREATE INDEX IF NOT EXISTS ix_bitacora_usuario
    ON bitacora (id_usuario, fecha_hora DESC);

CREATE OR REPLACE FUNCTION fn_auditar_sprint1()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO iqbf, pg_catalog, pg_temp
AS $$
DECLARE
  v_actor_text TEXT := current_setting('iqbf.actor_id', true);
  v_request_text TEXT := current_setting('iqbf.request_id', true);
  v_old JSONB;
  v_new JSONB;
  v_id TEXT;
BEGIN
  -- Nunca copie credenciales (ni siquiera hashes) a la bitácora.
  v_old := CASE
    WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) - 'contrasena'
  END;
  v_new := CASE
    WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) - 'contrasena'
  END;
  v_id := COALESCE(
      v_new ->> ('id_' || TG_TABLE_NAME),
      v_old ->> ('id_' || TG_TABLE_NAME),
      v_new ->> 'codigo',
      v_old ->> 'codigo',
      v_new ->> 'id_presentacion',
      v_old ->> 'id_presentacion',
      v_new ->> 'id_insumo',
      v_old ->> 'id_insumo',
      v_new ->> 'id_usuario',
      v_old ->> 'id_usuario'
  );

  INSERT INTO bitacora (
      id_usuario, accion, entidad, entidad_id,
      valores_antes, valores_despues, request_id, origen
  ) VALUES (
      CASE WHEN v_actor_text ~ '^[0-9]+$' THEN v_actor_text::integer END,
      TG_OP, TG_TABLE_NAME, v_id, v_old, v_new,
      CASE
        WHEN v_request_text ~
          '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$'
        THEN v_request_text::uuid
      END,
      CASE WHEN v_actor_text ~ '^[0-9]+$' THEN 'API' ELSE 'BD' END
  );

  RETURN COALESCE(NEW, OLD);
END
$$;

DO $$
DECLARE
  v_tabla TEXT;
BEGIN
  FOREACH v_tabla IN ARRAY ARRAY[
      'usuario', 'usuario_rol', 'usuario_alcance',
      'establecimiento', 'carrera', 'laboratorio', 'ubicacion',
      'investigador', 'insumo', 'presentacion', 'densidad_vigencia'
  ]
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS tg_aud_%I ON %I', v_tabla, v_tabla);
    EXECUTE format(
      'CREATE TRIGGER tg_aud_%I AFTER INSERT OR UPDATE OR DELETE ON %I '
      'FOR EACH ROW EXECUTE FUNCTION fn_auditar_sprint1()',
      v_tabla, v_tabla
    );
  END LOOP;
END
$$;

