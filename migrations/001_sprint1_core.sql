CREATE OR REPLACE FUNCTION normalizar_busqueda(valor TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
    SELECT lower(
      public.unaccent('public.unaccent'::regdictionary, coalesce(valor, ''))
    )
$$;

-- Organización: se preservan CARRERA y LABORATORIO y se añaden únicamente las
-- entidades que el Sprint 1 exige y que no existían en el MVP.
CREATE TABLE IF NOT EXISTS establecimiento (
    id_establecimiento  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(30) NOT NULL UNIQUE,
    nombre              VARCHAR(160) NOT NULL,
    estado              VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    vigencia_desde      DATE NOT NULL DEFAULT CURRENT_DATE,
    vigencia_hasta      DATE,
    CONSTRAINT ck_establecimiento_estado
      CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT ck_establecimiento_vigencia
      CHECK (vigencia_hasta IS NULL OR vigencia_hasta >= vigencia_desde)
);

ALTER TABLE carrera
    ADD COLUMN IF NOT EXISTS codigo VARCHAR(30),
    ADD COLUMN IF NOT EXISTS vigencia_desde DATE NOT NULL DEFAULT CURRENT_DATE,
    ADD COLUMN IF NOT EXISTS vigencia_hasta DATE;

UPDATE carrera
   SET codigo = concat('CAR-', lpad(id_carrera::text, 4, '0'))
 WHERE codigo IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_carrera_codigo_normalizado
    ON carrera (normalizar_busqueda(codigo));

ALTER TABLE laboratorio
    ADD COLUMN IF NOT EXISTS codigo VARCHAR(30),
    ADD COLUMN IF NOT EXISTS id_establecimiento INTEGER
