CREATE TABLE IF NOT EXISTS usuario_rol (
    id_usuario  INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    codigo_rol  VARCHAR(30) NOT NULL REFERENCES rol(codigo) ON DELETE RESTRICT,
    asignado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    asignado_por INTEGER REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    PRIMARY KEY (id_usuario, codigo_rol)
);

INSERT INTO usuario_rol (id_usuario, codigo_rol)
SELECT id_usuario,
       CASE rol
         WHEN 'DOCIMASIA' THEN 'OPERADOR_DOCIMASIA'
         WHEN 'ADMIN' THEN 'ADMIN_TECNICO'
         ELSE 'AUDITOR'
       END
  FROM usuario u
 WHERE NOT EXISTS (
       SELECT 1
         FROM usuario_rol ur
        WHERE ur.id_usuario = u.id_usuario
 )
ON CONFLICT DO NOTHING;

